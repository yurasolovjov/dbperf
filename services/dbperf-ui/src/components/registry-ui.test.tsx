it('parses supported YAML layouts, units, defaults and invalid inputs',()=>{
 expect(()=>parseYAML('hello')).toThrow('ожидается список targets');expect(()=>parseYAML('targets: {}')).toThrow()
 const rows=parseYAML('targets:\n - name: a\n   dsn: postgres://db/a\n   id: 7\n   interval: 2m\n   statement_timeout: 500ms\n   enabled: false\n   labels: {x: 1}\n - name: b\n   dsn: postgres://db/b\n   interval_sec: 10\n   statement_timeout_ms: 300\n - name: c\n   dsn: postgres://db/c\n   interval: 1h\n   statement_timeout: 2s\n - name: d\n   dsn: postgres://db/d\n   interval: ""\n   statement_timeout: null\n - null\n - name: e\n   dsn: postgres://db/e\n   interval: nonsense\n - name: f\n   dsn: postgres://db/f\n   interval: 10s\n   statement_timeout: bogus')
 expect(rows[0].input).toMatchObject({targetId:7,intervalSec:120,statementTimeoutMs:500,enabled:false,labels:{x:'1'}})
 expect(rows[1].input.intervalSec).toBe(10);expect(rows[2].input.intervalSec).toBe(3600)
 expect(rows[3].error).toBeNull();expect(rows[4].error).toContain('имя');expect(rows[5].error).toContain('длительность');expect(rows[6].error).toContain('длительность')
 expect(parseYAML('- name: a\n  dsn: postgres://db/a\n  interval: 10')[0].error).toBeNull()
})
